const fallback = 'Можно начать с пары предложений: что хотите создать, для кого и где это будет использоваться. Остальное уточните позже.';
const hints = Object.freeze({
  'Арт-объекты': 'Для обсуждения пригодятся фото площадки, примерные размеры объекта и образ, который вы хотите передать.',
  'Корпоративные заказы': 'Для оценки укажите, кому предназначен подарок, сколько экземпляров нужно и к какой дате. Логотип можно приложить к сообщению.',
  'Дизайн интерьеров': 'Укажите тип помещения, примерную площадь и что хотите изменить. Если есть план или фотографии, приложите их к сообщению.',
  'Парковая и монументальная скульптура': 'Опишите образ, высоту и место установки. Фото площадки поможет обсудить масштаб и монтаж.',
  'Промышленный дизайн': 'Опишите назначение изделия, его размеры и условия использования. Укажите, нужен ли прототип.',
  'Награды': 'Назовите событие, тираж, дату вручения и символику, которую важно сохранить.',
  'Макетирование': 'Что должен показать макет? Если знаете, укажите масштаб, габариты и нужную детализацию.'
});

export function briefGuidance(direction) {
  return Object.hasOwn(hints, direction) ? hints[direction] : fallback;
}

export function updateBriefGuidance({direction, helper}) {
  const text = briefGuidance(direction);
  if (helper.textContent !== text) helper.textContent = text;
}
